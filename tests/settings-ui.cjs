const { app, BrowserWindow, ipcMain, screen } = require('electron');
const fs = require('node:fs'), os = require('node:os'), path = require('node:path');
const assert = require('node:assert/strict');
app.setPath('userData', fs.mkdtempSync(path.join(os.tmpdir(), 'lume-settings-')));
require('../main');
let stage = 'startup';
setTimeout(() => { console.error('Settings test watchdog', stage, BrowserWindow.getAllWindows().map(win => ({ url: win.webContents.getURL(), loading: win.webContents.isLoading() }))); app.exit(1); }, 45000).unref();
let scans = 0, batteries = 0, pendingReads = 0;
for (const key of ['scan-desktop', 'system-info:battery', 'desktop-integration:pending', 'get-icon', 'list-apps']) ipcMain.removeHandler(key);
ipcMain.handle('list-apps', () => ({ items: [] }));
ipcMain.handle('scan-desktop', () => { scans++; return { items: [] }; });
ipcMain.handle('system-info:battery', () => { batteries++; return { level: 80 }; });
ipcMain.handle('desktop-integration:pending', () => { pendingReads++; return { items: [] }; });
ipcMain.handle('get-icon', () => null);
const pause = (ms = 30) => new Promise(resolve => setTimeout(resolve, ms));
async function until(check, name) { for (let i = 0; i < 150; i++) { if (await check()) return; await pause(); } throw new Error('Timed out: ' + name); }
const run = (win, source) => win.webContents.executeJavaScript(source);
async function ready(win) {
  if (win.webContents.isLoading()) await new Promise(resolve => win.webContents.once('did-finish-load', resolve));
  await run(win, 'window.dockReady');
}
app.whenReady().then(async () => {
  const dock = BrowserWindow.getAllWindows()[0];
  const js = source => run(dock, source);
  const errors = [];
  const watch = win => win.webContents.on('console-message', e => { if (e.level === 'error') errors.push(e.message); });
  watch(dock);
  try {
    await ready(dock); stage = 'open';
    await js('settings.autoHide=true;save();window.dockAPI.setAutoHide(true)');
    const initialScans = scans, initialPending = pendingReads;
    await js('launcher.open()');
    await js('window.dockAPI.openSettings()');
    let panel = BrowserWindow.getAllWindows().find(win => win !== dock);
    assert.ok(panel);
    watch(panel); await ready(panel); stage = 'preview'; await until(() => panel.isVisible(), 'settings visible');
    const prefs = source => run(panel, source);
    assert.equal(panel.isMovable(), true); assert.equal(panel.isResizable(), true);
    assert.equal(dock.isMovable(), false);
    assert.equal(dock.getBounds().height, 188);
    assert.equal(await js('launcher.isOpen()'), false, 'opening settings from the native entry point closes the launcher');
    assert.equal(await js('getComputedStyle(document.querySelector(".dock")).visibility'), 'visible');
    assert.equal(await prefs('getComputedStyle(document.querySelector(".panel-header")).webkitAppRegion'), 'drag');
    assert.equal(await prefs('getComputedStyle(document.querySelector("#closeSettings")).webkitAppRegion'), 'no-drag');
    assert.equal(await prefs('runningTimer===null&&timeTimer===null&&batteryTimer===null&&lyricsTimer===null'), true);
    assert.equal(scans, initialScans); assert.equal(pendingReads, initialPending);
    assert.equal(await prefs('document.querySelectorAll("#dockRow .dock-item").length'), 0);
    await pause(1000); assert.equal(dock.isVisible(), true, 'auto hide is suspended during preview');
    const bounds = panel.getBounds();
    assert.ok(bounds.y + bounds.height <= dock.getBounds().y, 'initial settings placement leaves the entire Dock visible');
    panel.setBounds({ x: bounds.x + 30, y: bounds.y + 20 });
    const moved = panel.getBounds();
    let settingsBoundsWrites = 0;
    const setSettingsBounds = panel.setBounds.bind(panel);
    panel.setBounds = (...args) => { settingsBoundsWrites++; return setSettingsBounds(...args); };
    const expectedDockWidth = percent => Math.min(Math.min(Math.max(Math.round(screen.getPrimaryDisplay().workArea.width * percent / 100), 600), 1080) + 192, screen.getPrimaryDisplay().workArea.width - 16);
    await js('openSettings()');
    assert.equal(BrowserWindow.getAllWindows().length, 2, 'repeated open reuses the settings window');
    assert.deepEqual(panel.getBounds(), moved, 'reopening preserves drag position');
    await prefs(`(async()=>{for(const [id,value] of Object.entries({iconSize:72,dockWidth:80,glassRadius:38,glassOpacity:61,glassBlur:0,glassHighlight:0,glassShadow:0,accentColor:'#ff9f0a'})) {const c=document.getElementById(id);c.value=value;c.dispatchEvent(new Event('input',{bubbles:true}));}})()`);
    await until(() => js('settings.iconSize===72&&settings.dockWidth===80&&settings.glassRadius===38&&settings.glassBlur===0&&settings.accentColor==="#FF9F0A"'), 'live appearance');
    assert.equal(dock.getBounds().height, 202);
    assert.equal(dock.getBounds().width, expectedDockWidth(80));
    assert.deepEqual(panel.getBounds(), moved, 'increasing Dock size does not resize the settings window');
    assert.equal(await js('document.documentElement.style.getPropertyValue("--icon-size")'), '72px');
    assert.equal(await js('dockShell.style.getPropertyValue("--dock-radius")'), '38px');
    assert.equal(await js('dockShell.style.getPropertyValue("--dock-blur")'), '0px');
    await prefs('document.querySelector("#iconSize").value=40;document.querySelector("#iconSize").dispatchEvent(new Event("input"));document.querySelector("#dockWidth").value=40;document.querySelector("#dockWidth").dispatchEvent(new Event("input"))');
    await until(() => js('settings.iconSize===40&&settings.dockWidth===40'), 'smaller Dock live update');
    assert.equal(dock.getBounds().height, 147);
    assert.equal(dock.getBounds().width, expectedDockWidth(40));
    assert.equal(await js('document.documentElement.style.getPropertyValue("--icon-size")'), '40px');
    assert.deepEqual(panel.getBounds(), moved, 'decreasing Dock size does not resize the settings window');
    assert.equal(settingsBoundsWrites, 0, 'Dock changes never write native settings bounds, even when platform bounds conversion differs');
    await prefs('themeSelect.value="light";themeSelect.dispatchEvent(new Event("change"))');
    await until(() => js('document.documentElement.dataset.theme==="light"'), 'live theme');
    await prefs('document.querySelector("#addSeparator").click()');
    await until(() => js('items.at(-1).type==="separator"'), 'separator sync');
    await js('addDroppedTargets(["C:/Apps/FromDock.exe"])');
    await until(() => prefs('items.at(-1).target==="C:/Apps/FromDock.exe"'), 'Dock additions sync back');
    await prefs('document.querySelector("#addButton").click();document.querySelector("#addForm").elements.name.value="From Settings";document.querySelector("#addForm").elements.target.value="C:/Apps/FromSettings.exe";document.querySelector("#addForm").requestSubmit()');
    await until(() => js('items.at(-1).target==="C:/Apps/FromSettings.exe"'), 'manual add sync');
    // A recent-use save and a slider update must preserve both independently changed fields.
    await prefs('document.querySelector("#iconSize").value=48;document.querySelector("#iconSize").dispatchEvent(new Event("input"))');
    await js('recordRecent(items.find(item=>item.target==="C:/Apps/FromDock.exe"));save()');
    await until(() => js('settings.iconSize===48'), 'concurrent setting and recent write');
    await until(() => prefs('recentItems[0]?.target==="C:/Apps/FromDock.exe"'), 'recent sync back');
    await prefs('document.querySelector("#manageList .manage-item:last-child .remove-item").click()');
    await until(() => js('!items.some(item=>item.target==="C:/Apps/FromSettings.exe")'), 'remove sync');
    await prefs('document.querySelector("#systemInfoToggle").click()');
    await until(() => js('timeTimer!==null&&batteryTimer!==null'), 'Dock polling remains active');
    assert.equal(await prefs('timeTimer===null&&batteryTimer===null&&runningTimer===null'), true);
    assert.ok(batteries > 0);
    // Two dialogs close independently; Esc in a dialog must not also close settings.
    await prefs('openAddDialog();document.dispatchEvent(new KeyboardEvent("keydown",{key:"Escape",bubbles:true}))');
    assert.equal(panel.isDestroyed(), false);
    await prefs('addDialog.close()');
    panel.setBounds({ width: 620, height: 360 }); await pause(250);
    assert.equal(await prefs('document.querySelector(".panel-body").scrollHeight>document.querySelector(".panel-body").clientHeight'), true);
    assert.equal(await prefs('document.querySelector("#closeSettings").getBoundingClientRect().bottom<innerHeight'), true);
    panel.setBounds(moved); await pause(250);
    const docs = path.join(__dirname, '../docs');
    fs.writeFileSync(path.join(docs, 'floating-settings.png'), (await panel.capturePage()).toPNG());
    fs.writeFileSync(path.join(docs, 'floating-settings-dock.png'), (await dock.capturePage()).toPNG());
    const panelContents = panel.webContents;
    stage = 'close'; await prefs('setTimeout(()=>document.getElementById("closeSettings").click(),0)'); await until(() => panel.isDestroyed(), 'close destroys renderer');
    assert.equal(panelContents.isDestroyed(), true);
    assert.equal(BrowserWindow.getAllWindows().length, 1); assert.equal(dock.isDestroyed(), false);
    stage = 'reopen'; await js('openSettings()'); panel = BrowserWindow.getAllWindows().find(win => win !== dock); await ready(panel);
    assert.equal(await run(panel, 'settings.iconSize'), 48);
    assert.deepEqual(panel.getBounds(), moved, 'position and size remembered in this session');
    panel.close(); await until(() => panel.isDestroyed(), 'close again');
    // Reload the Dock from persistent storage without an open settings renderer.
    stage = 'reload';
    // Keep the reload fixture visible; normal auto-hide is restored on settings close.
    await js('settings.autoHide=false;save();window.dockAPI.setAutoHide(false)');
    const loaded = new Promise(resolve => dock.webContents.once('did-finish-load', resolve)); dock.reload(); await loaded; await js('window.dockReady');
    assert.equal(await js('settings.iconSize'), 48);
    assert.equal(await js('recentItems[0]?.target'), 'C:/Apps/FromDock.exe');
    assert.equal(await js('items.some(item=>item.target==="C:/Apps/FromSettings.exe")'), false);
    assert.deepEqual(errors, []);
    console.log('Floating settings passed: movable/resizable native window, live Dock preview, auto-hide suspension, shared items/preferences/recent state, single polling owner, close/reopen and persisted reload.');
    app.exit(0);
  } catch(error) { console.error(error); app.exit(1); }
});
