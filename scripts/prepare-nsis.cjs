const fs = require('node:fs');
const path = require('node:path');

// Keep electron-builder's installer behavior, replacing only legacy uninstall execution.
// An old uninstaller uses Rename into its $PLUGINSDIR; that requires the same volume.
const templates = path.join(path.dirname(require.resolve('app-builder-lib/package.json')), 'templates/nsis');
function replaceOnce(source, before, after) {
  if (source.split(before).length !== 2) throw new Error('NSIS template changed; review the uninstall patch before building');
  return source.replace(before, after);
}
function patchedInstaller(originalScript) {
  let utility = fs.readFileSync(path.join(templates, 'include/installUtil.nsh'), 'utf8');
  utility = replaceOnce(utility,
    '  StrCpy $uninstallerFileNameTemp "$PLUGINSDIR\\old-uninstaller.exe"\n  !insertmacro copyFile "$uninstallerFileName" "$uninstallerFileNameTemp"',
    '  File /oname=$PLUGINSDIR\\lume-upgrade-uninstall.ps1 "${PROJECT_DIR}/scripts/upgrade-uninstall.ps1"\n  File /oname=$PLUGINSDIR\\stop-installed-app.ps1 "${PROJECT_DIR}/scripts/stop-installed-app.ps1"');
  utility = replaceOnce(utility,
    '    ExecWait \'"$uninstallerFileNameTemp" /S /KEEP_APP_DATA $0 _?=$installationDir\' $R0\n    ifErrors TryInPlace CheckResult\n\n    TryInPlace:\n      # the execution failed - might have been caused by some group policy restrictions\n      # we try to execute the uninstaller in place\n      ExecWait \'"$uninstallerFileName" /S /KEEP_APP_DATA $0 _?=$installationDir\' $R0\n      ifErrors DoesNotExist',
    '    nsExec::ExecToStack /TIMEOUT=120000 \'"$SYSDIR\\WindowsPowerShell\\v1.0\\powershell.exe" -NoLogo -NoProfile -NonInteractive -ExecutionPolicy Bypass -File "$PLUGINSDIR\\lume-upgrade-uninstall.ps1" -Uninstaller "$uninstallerFileName" -InstallDirectory "$installationDir" -UninstallArguments "$0"\'\n    Pop $R0\n    Pop $R9\n    ${if} $R0 != 0\n      MessageBox MB_OK|MB_ICONEXCLAMATION "旧版卸载未完成（代码 $R0）。请查看 %LOCALAPPDATA%\\Lume Dock\\InstallerLogs 中的日志。配置和快捷方式数据不会主动清除。"\n      SetErrorLevel 2\n      Quit\n    ${endif}\n    ClearErrors');
  utility = replaceOnce(utility, '  Var /Global uninstallerFileNameTemp\n', '');
  utility = replaceOnce(utility, '    CheckResult:\n', '');
  utility = replaceOnce(utility, '  DoesNotExist:\n    SetErrors\n', '');
  const script = originalScript ?? fs.readFileSync(path.join(templates, 'installer.nsi'), 'utf8');
  return '; Generated by prepare-nsis.cjs. Do not edit.\n' + replaceOnce(script, '  !include "installUtil.nsh"', utility);
}
if (require.main === module) {
  const output = path.join(__dirname, 'generated-installer.nsi');
  fs.writeFileSync(output, patchedInstaller());
  console.log('Prepared same-volume legacy upgrade installer');
}
module.exports = { patchedInstaller, replaceOnce };
